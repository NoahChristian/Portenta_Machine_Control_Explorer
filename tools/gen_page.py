#!/usr/bin/env python3
"""Generate app/src/web_gen/page_index.h from web/index.html.

    python tools/gen_page.py            regenerate
    python tools/gen_page.py --check    fail if the header is stale

The generated header is COMMITTED, deliberately, and so is not in .gitignore:
--check can only compare against a file in the tree, so ignoring it would
disable the drift guard that is the reason for generating it - and a committed
copy means the firmware builds on a machine with no Python.

WHAT THIS IS NOW. A thin wrapper around tools/mkhtml.py in the
Arduino_HTTP_HTML repository, which is the generator for the HtmlTpl SSI
engine this panel renders with. The real work is there: it strips the
design-time preview bodies, VALIDATES every <!--#v name--> against the registry
in app/src/page_vars.cpp, hashes the result, and writes the page out as a raw
string literal the engine parses in place.

WHAT THIS USED TO BE, AND WHY IT WENT. A 130-line script that turned
web/index.html into a C array of bytes, which the firmware served verbatim
while JavaScript on the page polled /state.json and built every table in the
browser. It embedded markup in C and checked nothing: a misspelled field name
produced an empty cell, in one branch, with no error at build time and no error
at run time. The whole point of the generator in the library is the opposite -
a name that does not exist in the registry fails the build and names the line.

THE REGISTRY VALIDATION IS THE REASON THIS RUNS AT ALL. Without --registry the
tool happily emits a page full of tags that will fault on the device, and the
symptom is a page with holes in it rather than a build that stopped. So the
registry is not optional here and the path is not a parameter.

WHERE THE LIBRARY IS. Beside this repository by default, which is how the
sketchbook is laid out; override with HTMLTPL_DIR. app/CMakeLists.txt resolves
it the same way and fails the build with the same message, because a checkout
that can compile the engine but not regenerate its pages would be a build that
serves whatever page was committed last.
"""
import argparse
import os
import pathlib
import re
import subprocess
import sys

# THE OLDEST ENGINE THIS REPOSITORY CAN BE GENERATED BY, and why it is 0.10.0
# rather than something earlier.
#
# The engine's generated headers used to include <Arduino.h>; they now include
# <HtmlTplPort.h>, which is the seam that lets the same template serve a Zephyr
# firmware. That change landed in Arduino_HTTP_HTML commit dd1e665 -- UNDER
# VERSION 0.9.2, which the two commits before it also carried.
#
# So 0.9.2 IS AN AMBIGUOUS VERSION: two different generated-output behaviors
# answer to that one number, and a floor of ">= 0.9.2" would be unsound because
# it admits the half that does not work here. 0.10.0 is the first version that
# unambiguously contains the new seam.
#
# This is the defect this check exists for, not a hypothetical. The engine
# changed its output and bumped nothing, a consumer's `--check` started failing,
# and the cause was three commits away in another repository with no version
# number to point at. A path-based dependency that records no version cannot say
# what it was built against, and cannot notice that it moved.
ENGINE_MIN = (0, 11, 0)


def parse_version(text):
    """Return (major, minor, patch) from a library.properties body, or None."""
    m = re.search(r"(?m)^version\s*=\s*([0-9]+(?:\.[0-9]+)*)", text)
    if not m:
        return None
    parts = [int(p) for p in m.group(1).split(".")]
    while len(parts) < 3:
        parts.append(0)
    return tuple(parts[:3])


def check_engine_version(lib):
    """Refuse an engine older than ENGINE_MIN, naming both versions.

    A MISSING OR UNREADABLE version is refused too, not waved through. "I could
    not tell" and "it is new enough" are different answers, and treating the
    first as the second is how a check reports clean about something it never
    read.
    """
    props = lib / "library.properties"
    want = ".".join(str(n) for n in ENGINE_MIN)
    if not props.exists():
        print("gen_page: no library.properties at %s" % props, file=sys.stderr)
        print("  Cannot tell which engine version this is. %s or newer is "
              "required." % want, file=sys.stderr)
        return 1
    got = parse_version(props.read_text(encoding="utf-8", errors="replace"))
    if got is None:
        print("gen_page: no version= line in %s" % props, file=sys.stderr)
        print("  %s or newer is required." % want, file=sys.stderr)
        return 1
    if got < ENGINE_MIN:
        print("gen_page: Arduino_HTTP_HTML is too old", file=sys.stderr)
        print("  found    %s  at %s" % (".".join(str(n) for n in got), lib),
              file=sys.stderr)
        print("  required %s or newer" % want, file=sys.stderr)
        print("  Generated headers include <HtmlTplPort.h>, which older "
              "engines do not emit.", file=sys.stderr)
        return 1
    return 0

REPO = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_LIB = REPO.parent / "Arduino_HTTP_HTML"

# The page carries the board drawing, so it is bigger than a page of tables and
# smaller than the 62 KB of flat SVG the previous design embedded. 32768 is the
# tool's default and this page is already past it.
#
# RAISED FROM 65536 ON 2026-11-16, DELIBERATELY. That figure was chosen to
# leave room for "the write controls M4 adds"; since then the page has gained
# the temperature panel, a wire-level serial terminal and a Modbus decoder,
# and it was within 7 bytes of the limit. The failure mode that mattered was
# not the size - it was that the response to hitting the limit became shaving
# words off comments, which trades documentation for a number nobody chose
# deliberately.
#
# 98304 is 50% more, still small enough that a careless addition is noticed,
# and roughly 6% of slot0 on a board at 65%.
#
# RAISED AGAIN TO 131072 ON 2026-11-18, for the reason the paragraph above
# names rather than in spite of it. The page gained an encoder table and a CAN
# block - state, a send control, mode buttons and a receive window - and came
# out at 103,851 bytes. The choice at that point is to raise a number nobody
# chose deliberately or to start deleting the comments that explain the panel,
# and this file already recorded which of those is the real failure.
#
# 128 KB is about 8% of slot0 with the image at 71% of it, so the constraint
# that matters is still nowhere near. The budget's job is to make an
# ACCIDENTAL doubling visible, not to ration the page.
BUDGET = 131072


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="fail if the generated header is stale")
    args = ap.parse_args()

    lib = pathlib.Path(os.environ.get("HTMLTPL_DIR", DEFAULT_LIB))
    mkhtml = lib / "tools" / "mkhtml.py"
    if not mkhtml.exists():
        print("gen_page: Arduino_HTTP_HTML not found at %s" % lib,
              file=sys.stderr)
        print("The panel is a TEMPLATE rendered on the board, not markup "
              "assembled in C, so the", file=sys.stderr)
        print("generator is not optional. Clone it beside this repository or "
              "set HTMLTPL_DIR.", file=sys.stderr)
        return 1

    rc = check_engine_version(lib)
    if rc:
        return rc

    cmd = [
        sys.executable, str(mkhtml),
        "--src", str(REPO / "web"),
        "--out", str(REPO / "app" / "src" / "web_gen"),
        "--registry", str(REPO / "app" / "src" / "page_vars.cpp"),
        "--budget", str(BUDGET),
        # app/src is C firmware, not a sketch directory: no api.d.ts, no
        # template-vars.json, no editor snippets.
        "--no-editor-files",
    ]
    if args.check:
        cmd.append("--check")

    return subprocess.call(cmd)


if __name__ == "__main__":
    sys.exit(main())
