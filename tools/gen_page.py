#!/usr/bin/env python3
"""Turn web/*.html into C headers the firmware can serve.

MARKUP IS AUTHORED AS HTML, NEVER ASSEMBLED IN C. That rule is carried from
a sibling project on this bench and it is the whole reason this script exists: a page built
by concatenating strings in a handler cannot be opened in a browser, cannot be
diffed usefully, and grows escaping bugs that only appear in one branch.

This is the minimal ancestor of that project's mkhtml.py. It does no template
substitution - dynamic values arrive through /state.json and are rendered by
the page's own script - so for now it only needs to embed bytes exactly.

    python tools/gen_page.py            regenerate
    python tools/gen_page.py --check    fail if a header is stale

--check is what the pre-commit hook runs. A generated header that no longer
matches its source compiles clean, flashes clean and serves the OLD page, which
is the kind of failure that wastes an afternoon.
"""
import argparse
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
OUT = ROOT / "app" / "src" / "web_gen"


def emit(src: pathlib.Path) -> tuple[str, str]:
    raw = src.read_bytes().replace(b"\r\n", b"\n")
    stem = src.stem.replace("-", "_")
    guard = f"PMC_PAGE_{stem.upper()}_H"
    sym = f"page_{stem}"
    digest = hashlib.sha256(raw).hexdigest()[:8]

    body = []
    for i in range(0, len(raw), 16):
        chunk = raw[i:i + 16]
        body.append("\t" + " ".join(f"0x{b:02x}," for b in chunk))

    text = f"""/*
 * GENERATED by tools/gen_page.py from web/{src.name} - DO NOT EDIT.
 *
 * Regenerate with:  python tools/gen_page.py
 *
 * The source is {len(raw)} bytes, sha256 {digest}. tools/gen_page.py --check
 * compares that digest and fails if this file is stale, because a header that
 * no longer matches its source serves the OLD page while compiling perfectly.
 *
 * SPDX-License-Identifier: MIT
 */
#ifndef {guard}
#define {guard}

#include <stddef.h>
#include <stdint.h>

#define {sym.upper()}_LEN {len(raw)}
#define {sym.upper()}_SHA "{digest}"

static const uint8_t {sym}[] = {{
{chr(10).join(body)}
}};

#endif /* {guard} */
"""
    return text, digest


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="fail if any generated header is stale")
    args = ap.parse_args()

    OUT.mkdir(parents=True, exist_ok=True)
    stale = []

    pages = sorted(WEB.glob("*.html"))
    if not pages:
        print("no pages in web/", file=sys.stderr)
        return 1

    for src in pages:
        text, digest = emit(src)
        dst = OUT / f"page_{src.stem.replace('-', '_')}.h"
        current = dst.read_text(encoding="utf-8") if dst.exists() else ""
        if current == text:
            print(f"  ok      {dst.relative_to(ROOT)}  ({digest})")
            continue
        if args.check:
            stale.append(dst.relative_to(ROOT))
            print(f"  STALE   {dst.relative_to(ROOT)}", file=sys.stderr)
            continue
        dst.write_text(text, encoding="utf-8", newline="\n")
        print(f"  wrote   {dst.relative_to(ROOT)}  ({digest})")

    if stale:
        print("", file=sys.stderr)
        print("Generated headers are stale. Run:  python tools/gen_page.py",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
